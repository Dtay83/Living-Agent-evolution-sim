/**
 * Generate a comprehensive web-enhanced explanation
 */
export function generateWebEnhancedExplanation(
  agent: Agent,
  subject: { type: 'invention' | 'physics' | 'math'; item: Invention | PhysicsConcept | MathConcept },
  unlockedMath: MathConcept[],
  unlockedPhysics: PhysicsConcept[],
  tick: number
): { explanation: AgentExplanation; webSearch: WebSearchResult } {
  let explanation: AgentExplanation;
  let webSearch: WebSearchResult;

  if (subject.type === 'invention') {
    const invention = subject.item as Invention;
    explanation = explainInvention(agent, invention, unlockedMath, unlockedPhysics, tick);
    webSearch = searchForInventionTerms(invention, unlockedMath, unlockedPhysics);
  } else if (subject.type === 'physics') {
    const concept = subject.item as PhysicsConcept;
    explanation = explainPhysicsDiscovery(agent, concept, unlockedMath, unlockedPhysics, tick);
    webSearch = searchForPhysicsTerms(concept, unlockedMath);
  } else {
    const concept = subject.item as MathConcept;
    explanation = explainMathDiscovery(agent, concept, unlockedMath, unlockedPhysics, tick);
    webSearch = searchForMathTerms(concept, unlockedPhysics);
  }

  // Enhance the explanation with web search results
  explanation.content += `\n\n🔬 Scientific Context: ${webSearch.enhancedExplanation}`;
  explanation.content += `\n\n📚 Related terms: ${webSearch.suggestedTerms.slice(0, 5).join(', ')}`;

  return { explanation, webSearch };
}

