/**
 * Determine the sophistication level based on available knowledge
 */
function calculateSophisticationLevel(
  unlockedMath: MathConcept[],
  unlockedPhysics: PhysicsConcept[],
  agent: Agent
): number {
  const mathComplexity = unlockedMath.reduce((sum, c) => sum + c.complexity, 0) / Math.max(1, unlockedMath.length);
  const physicsComplexity = unlockedPhysics.reduce((sum, c) => sum + c.complexity, 0) / Math.max(1, unlockedPhysics.length);
  
  const knowledgeLevel = (mathComplexity + physicsComplexity) / 2;
  const creativityBonus = agent.genes.creativity * 2;
  const curiosityBonus = agent.genes.curiosity * 1.5;
  
  return Math.min(10, Math.max(1, Math.round(knowledgeLevel + creativityBonus + curiosityBonus)));
}

/**
 * Get the appropriate template tier based on sophistication
 */
function getTemplateTier(sophistication: number): 'basic' | 'intermediate' | 'advanced' | 'transcendent' {
  if (sophistication >= 9) return 'transcendent';
  if (sophistication >= 6) return 'advanced';
  if (sophistication >= 3) return 'intermediate';
  return 'basic';
}

/**
 * Select random item from array
 */
function randomChoice<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/**
 * Generate a mathematical component of an explanation
 */
function generateMathComponent(
  unlockedMath: MathConcept[],
  subject: ExplanationSubject,
  tier: 'basic' | 'intermediate' | 'advanced' | 'transcendent'
): { text: string; conceptsUsed: string[] } {
  if (unlockedMath.length === 0) {
    return { text: '', conceptsUsed: [] };
  }

  const conceptsUsed: string[] = [];
  let template = randomChoice(MATH_EXPLANATION_TEMPLATES[tier]);
  
  // Find relevant concepts to reference
  const relevantConcepts = unlockedMath.filter(c => {
    // Match concepts to subject type
    if (subject.type === 'invention') {
      return c.category === 'optimization' || c.category === 'algebra' || c.category === 'arithmetic';
    }
    if (subject.type === 'observation') {
      return c.category === 'statistics' || c.category === 'geometry';
    }
    return true;
  });

  const conceptToUse = relevantConcepts.length > 0 ? randomChoice(relevantConcepts) : randomChoice(unlockedMath);
  conceptsUsed.push(conceptToUse.id);

  // Fill in template variables
  const variables: Record<string, string> = {
    quantity: String(Math.floor(Math.random() * 100) + 1),
    pattern: conceptToUse.description,
    concept: conceptToUse.name,
    theorem: conceptToUse.name,
    var: 'x',
    var1: 'x',
    var2: 'y',
    a: String(Math.floor(Math.random() * 10) + 1),
    b: String(Math.floor(Math.random() * 10) + 1),
    result: 'a new understanding',
    input: 'effort',
    output: 'result',
    rate: 'a measurable amount',
    conclusion: `the ${subject.name} works`,
    event: 'success',
    probability: `${Math.floor(Math.random() * 100)}%`,
    expression: `f(x)`,
    limit: '∞',
    value: 'convergence',
    phenomenon: subject.name,
    A: 'cause',
    B: 'effect',
    level: String(Math.floor(Math.random() * 5) + 1),
    insight: 'deeper truth',
    f: 'Ω',
    domain: 'input space',
    codomain: 'output space',
    principle: conceptToUse.description,
    object: subject.name,
    total: String(Math.floor(Math.random() * 100) + 10),
    parts: String(Math.floor(Math.random() * 10) + 2),
  };

  // Replace placeholders in template
  for (const [key, value] of Object.entries(variables)) {
    template = template.replace(new RegExp(`\\{${key}\\}`, 'g'), value);
  }

  return { text: template, conceptsUsed };
}

