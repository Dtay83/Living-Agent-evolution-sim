/**
 * EXPLANATION SYSTEM
 * 
 * Enables agents to explain their inventions and discoveries using
 * their mathematical and physics knowledge. Explanations become
 * more sophisticated as agents discover more concepts.
 * 
 * Features:
 * - Generate explanations based on available knowledge
 * - Use mathematical notation when math concepts are known
 * - Reference physics principles when physics concepts are known
 * - Evolve explanation complexity with consciousness level
 * - Share explanations between agents for knowledge transfer
 * - WEB SEARCH INTEGRATION: Agents can search for real scientific terms
 */

import type { Agent, Invention } from '../types';
import type { PhysicsConcept } from '../science-system/physics';
import type { MathConcept } from '../science-system/mathematics';
import type { AgentLanguageState } from '../speech-integration';

/**
 * An explanation generated by an agent
 */
export interface AgentExplanation {
  id: string;
  agentId: number;
  tick: number;
  subject: ExplanationSubject;
  content: string;
  mathConceptsUsed: string[];      // IDs of math concepts referenced
  physicsConceptsUsed: string[];   // IDs of physics concepts referenced
  sophisticationLevel: number;     // 1-10: How advanced the explanation is
  accuracy: number;                // 0-1: How scientifically accurate
  creativity: number;              // 0-1: How novel the explanation is
  understandableBy: number;        // Minimum vocab size needed to understand
}

/**
 * What is being explained
 */
export interface ExplanationSubject {
  type: 'invention' | 'physics_concept' | 'math_concept' | 'observation' | 'hypothesis';
  id: string;
  name: string;
}

