/**
 * Generate a Google search URL for a scientific query
 */
export function generateGoogleSearchUrl(query: string): string {
  const encodedQuery = encodeURIComponent(query);
  return `https://www.google.com/search?q=${encodedQuery}`;
}

/**
 * Generate a Wikipedia search URL for quick reference
 */
export function generateWikipediaUrl(term: string): string {
  const encodedTerm = encodeURIComponent(term.replace(/ /g, '_'));
  return `https://en.wikipedia.org/wiki/${encodedTerm}`;
}

/**
 * Get scientific terms related to a concept category
 */
export function getScientificTermsForCategory(category: string): { terms: string[]; relatedConcepts: string[] } {
  const normalized = category.toLowerCase().replace(/-/g, '_');
  return SCIENTIFIC_TERM_DATABASE[normalized] || {
    terms: ['Scientific method', 'Empirical research', 'Hypothesis testing'],
    relatedConcepts: ['Observation', 'Experimentation', 'Theory']
  };
}

/**
 * Search for proper scientific terms to explain an invention
 */
export function searchForInventionTerms(
  invention: Invention,
  unlockedMath: MathConcept[],
  unlockedPhysics: PhysicsConcept[]
): WebSearchResult {
  // Determine relevant categories based on invention type
  const relevantCategories: string[] = [];
  
  switch (invention.effect.type) {
    case 'energy_efficiency':
      relevantCategories.push('thermodynamics', 'optimization');
      break;
    case 'food_detection_range':
      relevantCategories.push('optics', 'electromagnetism', 'statistics');
      break;
    case 'reproduction_boost':
      relevantCategories.push('genetics', 'statistics', 'optimization');
      break;
    case 'defense':
      relevantCategories.push('mechanics', 'materials_science');
      break;
    case 'storage':
      relevantCategories.push('thermodynamics', 'optimization');
      break;
  }

  // Add categories from unlocked concepts
  const mathCategories = [...new Set(unlockedMath.map(c => c.category))];
  const physicsCategories = [...new Set(unlockedPhysics.map(c => c.category))];
  
  // Gather all related terms
  const allTerms: string[] = [];
  const allRelated: string[] = [];
  
  for (const cat of [...relevantCategories, ...mathCategories, ...physicsCategories]) {
    const { terms, relatedConcepts } = getScientificTermsForCategory(cat);
    allTerms.push(...terms);
    allRelated.push(...relatedConcepts);
  }

  // Create search query
  const searchQuery = `${invention.name} scientific explanation ${invention.effect.type.replace(/_/g, ' ')}`;
  const primaryTerm = allTerms[Math.floor(Math.random() * allTerms.length)] || 'physics';

  return {
    query: searchQuery,
    searchUrl: generateGoogleSearchUrl(searchQuery),
    suggestedTerms: [...new Set(allTerms)].slice(0, 10),
    relatedConcepts: [...new Set(allRelated)].slice(0, 10),
    enhancedExplanation: generateEnhancedExplanation(invention, allTerms, allRelated),
    wikipediaUrl: generateWikipediaUrl(primaryTerm),
    timestamp: Date.now()
  };
}

/**
 * Search for proper scientific terms to explain a physics discovery
 */
export function searchForPhysicsTerms(
  concept: PhysicsConcept,
  unlockedMath: MathConcept[]
): WebSearchResult {
  const { terms, relatedConcepts } = getScientificTermsForCategory(concept.category);
  
  // Add mathematical underpinnings
  const mathCategories = [...new Set(unlockedMath.map(c => c.category))];
  const mathTerms: string[] = [];
  
  for (const cat of mathCategories) {
    const mathData = getScientificTermsForCategory(cat);
    mathTerms.push(...mathData.terms.slice(0, 3));
  }

  const searchQuery = `${concept.name} physics ${concept.category}`;
  
  return {
    query: searchQuery,
    searchUrl: generateGoogleSearchUrl(searchQuery),
    suggestedTerms: [...terms, ...mathTerms.slice(0, 5)],
    relatedConcepts: relatedConcepts,
    enhancedExplanation: generatePhysicsEnhancedExplanation(concept, terms, relatedConcepts),
    wikipediaUrl: generateWikipediaUrl(concept.name),
    timestamp: Date.now()
  };
}

/**
 * Search for proper mathematical terms to explain a math discovery
 */
export function searchForMathTerms(
  concept: MathConcept,
  unlockedPhysics: PhysicsConcept[]
): WebSearchResult {
  const { terms, relatedConcepts } = getScientificTermsForCategory(concept.category);
  
  // Find physics applications - physics concepts that build on math
  const physicsApplications: string[] = [];
  for (const physics of unlockedPhysics) {
    // Check if this physics concept might use math (based on complexity)
    if (physics.complexity >= concept.complexity) {
      physicsApplications.push(physics.name);
    }
  }

  const searchQuery = `${concept.name} mathematics ${concept.category}`;
  
  return {
    query: searchQuery,
    searchUrl: generateGoogleSearchUrl(searchQuery),
    suggestedTerms: terms,
    relatedConcepts: [...relatedConcepts, ...physicsApplications.slice(0, 3)],
    enhancedExplanation: generateMathEnhancedExplanation(concept, terms, relatedConcepts),
    wikipediaUrl: generateWikipediaUrl(concept.name),
    timestamp: Date.now()
  };
}

/**
 * Generate an enhanced explanation using real scientific terminology
 */
function generateEnhancedExplanation(
  invention: Invention,
  terms: string[],
  relatedConcepts: string[]
): string {
  const term1 = terms[Math.floor(Math.random() * terms.length)] || 'scientific principles';
  const term2 = terms[Math.floor(Math.random() * terms.length)] || 'natural laws';
  const concept = relatedConcepts[Math.floor(Math.random() * relatedConcepts.length)] || 'fundamental physics';

  const templates = [
    `According to ${term1}, the ${invention.name} operates by leveraging ${concept}. ` +
    `This is analogous to how ${term2} manifests in natural systems.`,
    
    `The mechanism of ${invention.name} can be understood through ${term1}. ` +
    `The underlying principle relates to ${concept}, as described in modern ${term2}.`,
    
    `${invention.name} exemplifies the practical application of ${term1}. ` +
    `Its effectiveness stems from ${concept}, a cornerstone of ${term2}.`,
    
    `Through the lens of ${term1}, we can explain how ${invention.name} achieves its effect. ` +
    `The key insight involves ${concept} and its relationship to ${term2}.`
  ];

  return templates[Math.floor(Math.random() * templates.length)];
}

