/**
 * Generate a hypothesis about an observation
 */
export function generateHypothesis(
  agent: Agent,
  observation: string,
  unlockedMath: MathConcept[],
  unlockedPhysics: PhysicsConcept[],
  tick: number
): AgentExplanation {
  const subject: ExplanationSubject = {
    type: 'hypothesis',
    id: `hyp_${agent.id}_${tick}`,
    name: observation
  };

  const sophistication = calculateSophisticationLevel(unlockedMath, unlockedPhysics, agent);
  const tier = getTemplateTier(sophistication);
  
  const mathPart = generateMathComponent(unlockedMath, subject, tier);
  const physicsPart = generatePhysicsComponent(unlockedPhysics, subject, tier);
  
  const hypothesisStarters = [
    'I hypothesize that',
    'My theory is that',
    'I believe',
    'Evidence suggests that',
    'Based on my observations,',
  ];
  
  let content = `${randomChoice(hypothesisStarters)} ${observation}`;
  
  if (mathPart.text) {
    content += `. ${mathPart.text}`;
  }
  
  if (physicsPart.text) {
    content += ` ${physicsPart.text}`;
  }
  
  content += ` This requires further investigation.`;

  return {
    id: `exp_${agent.id}_${tick}_hypothesis`,
    agentId: agent.id,
    tick,
    subject,
    content,
    mathConceptsUsed: mathPart.conceptsUsed,
    physicsConceptsUsed: physicsPart.conceptsUsed,
    sophisticationLevel: sophistication,
    accuracy: 0.5 + agent.genes.curiosity * 0.3, // Hypotheses are uncertain
    creativity: agent.genes.creativity,
    understandableBy: Math.floor(sophistication * 5)
  };
}

/**
 * Check if one agent can understand another's explanation
 */
export function canUnderstandExplanation(
  listener: Agent,
  explanation: AgentExplanation,
  listenerLanguage: AgentLanguageState | undefined
): boolean {
  if (!listenerLanguage) {
    // Without language state, use basic intelligence check
    return listener.genes.curiosity + listener.genes.patience > 0.8;
  }
  
  // Check vocabulary size
  if (listenerLanguage.vocabularySize < explanation.understandableBy) {
    return false;
  }
  
  // Check if listener knows enough concepts
  const knownMathConcepts = explanation.mathConceptsUsed.length * 0.5;
  const knownPhysicsConcepts = explanation.physicsConceptsUsed.length * 0.5;
  
  return listenerLanguage.languageComplexity >= (knownMathConcepts + knownPhysicsConcepts);
}

/**
 * Simplify an explanation for a less sophisticated listener
 */
export function simplifyExplanation(
  explanation: AgentExplanation,
  targetSophistication: number
): string {
  if (targetSophistication >= explanation.sophisticationLevel) {
    return explanation.content;
  }
  
  // Generate simplified version
  const simplifiers = [
    (text: string) => text.replace(/\b\w{12,}\b/g, 'thing'), // Replace long words
    (text: string) => text.replace(/[∫∂Σ∞ω√π]/g, ''), // Remove math symbols
    (text: string) => text.split('.').slice(0, 2).join('.') + '.', // Shorten
    (text: string) => text.replace(/\d+\.\d+/g, 'some'), // Replace precise numbers
  ];
  
  let simplified = explanation.content;
  const stepsToSimplify = explanation.sophisticationLevel - targetSophistication;
  
  for (let i = 0; i < Math.min(stepsToSimplify, simplifiers.length); i++) {
    simplified = simplifiers[i](simplified);
  }
  
  return simplified;
}

