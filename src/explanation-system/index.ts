/**
 * Generate a complete explanation for an invention
 */
export function explainInvention(
  agent: Agent,
  invention: Invention,
  unlockedMath: MathConcept[],
  unlockedPhysics: PhysicsConcept[],
  tick: number
): AgentExplanation {
  const subject: ExplanationSubject = {
    type: 'invention',
    id: invention.id,
    name: invention.name
  };

  const sophistication = calculateSophisticationLevel(unlockedMath, unlockedPhysics, agent);
  const tier = getTemplateTier(sophistication);
  
  // Generate components
  const mathPart = generateMathComponent(unlockedMath, subject, tier);
  const physicsPart = generatePhysicsComponent(unlockedPhysics, subject, tier);
  
  // Combine into full explanation
  const intro = generateIntroduction(agent, invention, sophistication);
  const connector = randomChoice(CONNECTORS.cause);
  const conclusion = generateConclusion(invention, sophistication);
  
  let content = intro;
  
  if (mathPart.text) {
    content += ` ${randomChoice(CONNECTORS.addition)}, ${mathPart.text}`;
  }
  
  if (physicsPart.text) {
    content += ` ${randomChoice(CONNECTORS.comparison)}, from a physical perspective: ${physicsPart.text}`;
  }
  
  content += ` ${randomChoice(CONNECTORS.conclusion)}, ${conclusion}`;

  return {
    id: `exp_${agent.id}_${tick}_${invention.id}`,
    agentId: agent.id,
    tick,
    subject,
    content,
    mathConceptsUsed: mathPart.conceptsUsed,
    physicsConceptsUsed: physicsPart.conceptsUsed,
    sophisticationLevel: sophistication,
    accuracy: calculateAccuracy(unlockedMath.length + unlockedPhysics.length, sophistication),
    creativity: agent.genes.creativity,
    understandableBy: Math.floor(sophistication * 5)
  };
}

/**
 * Get human-readable description for an invention effect type
 */
function getEffectDescription(effect: Invention['effect']): string {
  switch (effect.type) {
    case 'energy_efficiency': return 'energy efficiency';
    case 'food_detection_range': return 'food detection';
    case 'reproduction_boost': return 'reproduction';
    case 'defense': return 'defense';
    case 'storage': return 'storage capacity';
    default: return 'survival';
  }
}

/**
 * Get the numeric value from an invention effect
 */
function getEffectValue(effect: Invention['effect']): number {
  switch (effect.type) {
    case 'energy_efficiency': return effect.multiplier;
    case 'food_detection_range': return effect.range;
    case 'reproduction_boost': return effect.bonus;
    case 'defense': return effect.protection;
    case 'storage': return effect.capacity;
    default: return 1;
  }
}

